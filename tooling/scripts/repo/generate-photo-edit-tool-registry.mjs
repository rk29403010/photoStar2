import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.cwd();
const pluginsRoot = join(root, 'src/services/photoEditing/tools/plugins');
const outputPath = join(root, 'src/services/photoEditing/generatedPhotoEditToolPluginRegistry.ts');
const uiOutputPath = join(root, 'src/ui/components/photo-editor/generatedPhotoEditToolUiRegistry.ts');
const suggestionOutputPath = join(root, 'src/ui/components/photo-editor/generatedPhotoEditToolSuggestionRegistry.ts');
const browserPreviewOutputPath = join(root, 'src/ui/components/photo-editor/generatedPhotoEditToolBrowserPreviewRegistry.ts');
const browserManifestOutputPath = join(root, 'src/ui/components/photo-editor/generatedPhotoEditToolBrowserManifestRegistry.ts');

function manifestForEntry(directory, entry) {
    const entryPath = join(directory, entry.name);
    if (entry.isDirectory()) { return manifests(entryPath); }
    return entry.name === 'manifest.ts' ? [entryPath] : [];
}

function manifests(directory) {
    return readdirSync(directory, { withFileTypes: true })
        .flatMap((entry) => manifestForEntry(directory, entry))
        .sort((left, right) => left.localeCompare(right));
}

function pluginImport(index, path) {
    return `import plugin${index} from '${path}';`;
}

function registryItems(paths) {
    return paths.map((_, index) => `    plugin${index},`);
}

function source(paths) {
    const imports = paths.map((filePath, index) => pluginImport(index, `./${relative(join(root, 'src/services/photoEditing'), filePath).replaceAll('\\', '/')}`));
    return ['// This file is generated by tooling/scripts/repo/generate-photo-edit-tool-registry.mjs. Do not edit.', "import type { PhotoEditToolPlugin } from './photoEditToolPlugin.ts';", ...imports, '', 'export const generatedPhotoEditToolPlugins: readonly PhotoEditToolPlugin[] = [', ...registryItems(paths), '];', ''].join('\n');
}

function uiSource(paths) {
    const imports = paths.map((filePath, index) => pluginImport(index, `../../../services/photoEditing/tools/plugins/${relative(pluginsRoot, filePath).replaceAll('\\', '/')}`));
    return ['// This file is generated by tooling/scripts/repo/generate-photo-edit-tool-registry.mjs. Do not edit.', "import type { PhotoEditToolUiPlugin } from './photoEditToolUiRegistry.ts';", ...imports, '', 'export const generatedPhotoEditToolUiPlugins: readonly PhotoEditToolUiPlugin[] = [', ...registryItems(paths), '];', ''].join('\n');
}

function discoveredFiles(directory, name) {
    return readdirSync(directory, { withFileTypes: true })
        .flatMap((entry) => {
            const entryPath = join(directory, entry.name);
            if (entry.isDirectory()) { return discoveredFiles(entryPath, name); }
            return entry.name === name ? [entryPath] : [];
        })
        .sort((left, right) => left.localeCompare(right));
}

function uiModules(directory) { return discoveredFiles(directory, 'ui.tsx'); }

function suggestionSource(paths) {
    const imports = paths.map((filePath, index) => pluginImport(index, `../../../services/photoEditing/tools/plugins/${relative(pluginsRoot, filePath).replaceAll('\\', '/')}`));
    return ['// This file is generated by tooling/scripts/repo/generate-photo-edit-tool-registry.mjs. Do not edit.', "import type { PhotoEditToolSuggestionPlugin } from './photoEditToolSuggestionRegistry.ts';", ...imports, '', 'export const generatedPhotoEditToolSuggestionPlugins: readonly PhotoEditToolSuggestionPlugin[] = [', ...registryItems(paths), '];', ''].join('\n');
}

function suggestionModules(directory) { return discoveredFiles(directory, 'automatic.ts'); }

function browserPreviewSource(paths) {
    const imports = paths.map((filePath, index) => pluginImport(index, `../../../services/photoEditing/tools/plugins/${relative(pluginsRoot, filePath).replaceAll('\\', '/')}`));
    return ['// This file is generated by tooling/scripts/repo/generate-photo-edit-tool-registry.mjs. Do not edit.', "import type { PhotoEditToolBrowserPreviewPlugin } from '../../../services/photoEditing/photoEditToolPlugin.ts';", ...imports, '', 'export const generatedPhotoEditToolBrowserPreviewPlugins: readonly PhotoEditToolBrowserPreviewPlugin[] = [', ...registryItems(paths), '];', ''].join('\n');
}

function browserPreviewModules(directory) { return discoveredFiles(directory, 'browserPreview.ts'); }

function browserManifestSource(serializedEntries) {
    return [
        '// This file is generated by tooling/scripts/repo/generate-photo-edit-tool-registry.mjs. Do not edit.',
        "import type { PhotoEditToolPlugin } from '../../../services/photoEditing/photoEditToolPlugin.ts';",
        '',
        "export type PhotoEditToolBrowserManifest = Pick<PhotoEditToolPlugin, 'id' | 'recipeVersion' | 'label' | 'icon' | 'group' | 'defaults' | 'controls' | 'capabilities' | 'help' | 'errorBoundaryDisplayName'>;",
        '',
        'export const generatedPhotoEditToolBrowserManifests: readonly PhotoEditToolBrowserManifest[] = ',
        JSON.stringify(serializedEntries, null, 4),
        ';',
        '',
    ].join('\n');
}

function serializableBrowserManifest(plugin, manifestPath) {
    const metadata = {
        id: plugin?.id,
        recipeVersion: plugin?.recipeVersion,
        label: plugin?.label,
        icon: plugin?.icon,
        group: plugin?.group,
        defaults: plugin?.defaults,
        controls: plugin?.controls ?? [],
        capabilities: plugin?.capabilities ?? {},
        help: plugin?.help,
        errorBoundaryDisplayName: plugin?.errorBoundaryDisplayName,
    };
    try {
        return JSON.parse(JSON.stringify(metadata));
    } catch (error) {
        const detail = error instanceof Error ? error.message : String(error);
        throw new Error(`photo edit tool manifest is not serializable: ${manifestPath}: ${detail}`);
    }
}

async function browserManifests(paths) {
    return Promise.all(paths.map(async (manifestPath) => {
        const manifest = await import(pathToFileURL(manifestPath).href);
        return serializableBrowserManifest(manifest.default, manifestPath);
    }));
}

if (!existsSync(pluginsRoot)) { throw new Error(`photo edit tool plug-in directory is missing: ${pluginsRoot}`); }

const pluginManifestPaths = manifests(pluginsRoot);
const expected = source(pluginManifestPaths);
const expectedUi = uiSource(uiModules(pluginsRoot));
const expectedSuggestions = suggestionSource(suggestionModules(pluginsRoot));
const expectedBrowserPreviews = browserPreviewSource(browserPreviewModules(pluginsRoot));
const expectedBrowserManifests = browserManifestSource(await browserManifests(pluginManifestPaths));
const isStale = !existsSync(outputPath)
    || readFileSync(outputPath, 'utf8') !== expected
    || !existsSync(uiOutputPath)
    || readFileSync(uiOutputPath, 'utf8') !== expectedUi
    || !existsSync(suggestionOutputPath)
    || readFileSync(suggestionOutputPath, 'utf8') !== expectedSuggestions
    || !existsSync(browserPreviewOutputPath)
    || readFileSync(browserPreviewOutputPath, 'utf8') !== expectedBrowserPreviews
    || !existsSync(browserManifestOutputPath)
    || readFileSync(browserManifestOutputPath, 'utf8') !== expectedBrowserManifests;

if (process.argv.includes('--check')) {
    if (isStale) { throw new Error('photo edit tool plug-in registry is stale; run pnpm.cmd run photo-tool:generate-registry'); }
} else {
    writeFileSync(outputPath, expected);
    writeFileSync(uiOutputPath, expectedUi);
    writeFileSync(suggestionOutputPath, expectedSuggestions);
    writeFileSync(browserPreviewOutputPath, expectedBrowserPreviews);
    writeFileSync(browserManifestOutputPath, expectedBrowserManifests);
}
