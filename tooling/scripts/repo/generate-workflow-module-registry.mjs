import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = process.cwd();
const pluginsRoot = join(root, 'src/services/workflowRuntime/modules/plugins');
const outputPath = join(root, 'src/services/workflowRuntime/generatedModulePluginRegistry.ts');
const checkOnly = process.argv.includes('--check');

function discoverManifestPaths(directory) {
    return readdirSync(directory, { withFileTypes: true })
        .flatMap((entry) => {
            const path = join(directory, entry.name);
            if (entry.isDirectory()) {
                return discoverManifestPaths(path);
            }
            return entry.name === 'manifest.ts' ? [path] : [];
        })
        .sort((left, right) => left.localeCompare(right));
}

function buildRegistrySource(manifestPaths) {
    const imports = manifestPaths.map((manifestPath, index) => {
        const specifier = `./${relative(join(root, 'src/services/workflowRuntime'), manifestPath).replaceAll('\\', '/').replace(/\.ts$/, '')}`;
        return `import plugin${index} from '${specifier}';`;
    });
    return [
        '// This file is generated by tooling/scripts/repo/generate-workflow-module-registry.mjs. Do not edit.',
        "import type { WorkflowModulePlugin } from './contracts';",
        ...imports,
        '',
        'export const generatedWorkflowModulePlugins: readonly WorkflowModulePlugin[] = [',
        ...manifestPaths.map((_, index) => `    plugin${index},`),
        '];',
        '',
    ].join('\n');
}

if (!existsSync(pluginsRoot)) {
    throw new Error(`workflow module plug-in directory is missing: ${pluginsRoot}`);
}
const expected = buildRegistrySource(discoverManifestPaths(pluginsRoot));
if (checkOnly) {
    if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== expected) {
        throw new Error('workflow module plug-in registry is stale; run pnpm.cmd run module:generate-registry');
    }
} else {
    writeFileSync(outputPath, expected);
}
